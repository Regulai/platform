/// <reference types="vitest/config" />
import { readdirSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath, URL } from "node:url"

import tailwindcss from "@tailwindcss/vite"
import react from "@vitejs/plugin-react"
import { defineConfig, type Plugin } from "vite"

const NODE_MODULES = fileURLToPath(new URL("./node_modules", import.meta.url))
// Packages that reach the build only as CSS (no module of theirs is in a JS chunk).
const CSS_PACKAGES = ["tailwindcss", "tw-animate-css"]
const COPIED = `regulAI chat island: third-party software in this build

Generated by the build from the packages it bundled (package-lock.json pins them).
Copied and adapted source, not in the list below:
- src/components/ui/*: generated with the shadcn CLI 4.22 (base-nova style) and edited.
- src/styles/vendor/shadcn-tailwind.css: shadcn 4.22.0 dist/tailwind.css, unmodified.
Both MIT License, Copyright (c) 2023 shadcn: the same text as @shadcn/react below.
`

/** The licenses of exactly what the build bundles, next to the files that contain it. */
function notices(): Plugin {
  return {
    name: "regulai-third-party-notices",
    apply: "build",
    generateBundle(_options, bundle) {
      const packages = new Map<string, string>(CSS_PACKAGES.map((name) => [name, join(NODE_MODULES, name)]))
      for (const chunk of Object.values(bundle)) {
        if (chunk.type !== "chunk") continue
        for (const id of Object.keys(chunk.modules)) {
          const match = id.replace(/\\/g, "/").match(/^(.*\/node_modules\/((?:@[^/]+\/)?[^/]+))\//)
          if (match) packages.set(match[2]!, match[1]!)
        }
      }
      // Code-point order and sorted listings: the same bytes on every OS and locale.
      const sections = [...packages.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([name, directory]) => {
        const manifest = JSON.parse(readFileSync(join(directory, "package.json"), "utf8")) as { version: string; license?: string }
        const file = readdirSync(directory).sort().find((entry) => /^licen[cs]e/i.test(entry))
        const text = file ? readFileSync(join(directory, file), "utf8").replace(/\r\n?/g, "\n").trim() : `License: ${manifest.license}`
        return `----------------------------------------------------------------------\n${name} ${manifest.version} (${manifest.license})\n\n${text}\n`
      })
      this.emitFile({ type: "asset", fileName: "THIRD-PARTY-NOTICES.txt", source: `${COPIED}\n${sections.join("\n")}` })
    },
  }
}

// Django serves the build from regulai/static/chat-app and resolves every entry,
// chunk and stylesheet through manifest.json (not .vite/: the installer bundle
// skips dot-directories). A relative base lets chunks load under any STATIC_URL.
export default defineConfig({
  base: "./",
  plugins: [react(), tailwindcss(), notices()],
  resolve: {
    alias: { "@": fileURLToPath(new URL("./src", import.meta.url)) },
  },
  build: {
    outDir: fileURLToPath(new URL("../../regulai/static/chat-app", import.meta.url)),
    emptyOutDir: true,
    manifest: "manifest.json",
    sourcemap: false,
    target: "es2022",
    assetsInlineLimit: 0,
    rollupOptions: {
      input: "src/main.tsx",
    },
  },
  test: {
    environment: "jsdom",
    include: ["src/**/*.test.{ts,tsx}"],
    setupFiles: ["src/test/setup.ts"],
    restoreMocks: true,
  },
})
