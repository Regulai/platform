import { expect, test } from "@playwright/test"

import { lab, lastTurn, prompt, send, watchErrors, watchNetwork } from "./helpers"

/* Journeys on the built island served by Django (lab fixture: synthetic data,
 * simulated provider transport, fixture agent events). Run serially: the lab
 * conversation grows with each journey. */

test.describe.configure({ mode: "serial" })

test("chat: the answer grows at the live edge, reading above holds, history is untouched", async ({ page, baseURL }) => {
  const net = watchNetwork(page, baseURL!)
  const errors = watchErrors(page)
  await page.goto(`/chat/${lab().chat}/`)
  const history = page.locator(".rg-md").first()
  await expect(history).toBeVisible()
  await history.evaluate((node) => { (node as HTMLElement & { __history?: boolean }).__history = true })
  expect(await history.locator(".rg-enter").count()).toBe(0)

  await send(page, "Explica el caso largo con ejemplos")
  const answer = lastTurn(page).locator(".rg-md")
  await expect(answer).toHaveAttribute("data-streaming", "")
  const viewport = page.getByRole("region", { name: "Mensajes" })
  await viewport.hover()
  await page.mouse.wheel(0, -900)
  await page.waitForTimeout(250)
  const before = await viewport.evaluate((node) => node.scrollTop)
  await page.waitForTimeout(900)
  expect(Math.abs((await viewport.evaluate((node) => node.scrollTop)) - before)).toBeLessThan(4)
  const jump = page.getByRole("button", { name: "Ir al final" })
  await expect(jump).toHaveAttribute("data-active", "true")
  await jump.click()

  await expect(lastTurn(page).getByRole("button", { name: "Copiar respuesta" })).toBeVisible({ timeout: 30_000 })
  await expect(answer).not.toHaveAttribute("data-streaming")
  expect(await history.evaluate((node) => (node as HTMLElement & { __history?: boolean }).__history)).toBe(true)
  expect(net.posts("/send/")).toHaveLength(1)
  expect(net.foreign()).toEqual([])
  expect(errors).toEqual([])
})

test("chat: copy is confirmed only by the clipboard and copies protected labels", async ({ page, context }) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"])
  await page.goto(`/chat/${lab().chat}/`)
  const turn = page.locator("article[data-turn]").filter({ has: page.locator(".rg-redacted") }).first()
  const copy = turn.getByRole("button", { name: "Copiar respuesta" })
  await copy.click()
  await expect(turn.getByRole("button", { name: "Copiado" })).toBeVisible()
  const copied = await page.evaluate(() => navigator.clipboard.readText())
  expect(copied).toContain("[correo protegido]")
  expect(copied).not.toContain("REGULAI_")
})

